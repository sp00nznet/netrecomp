// Writes nrgen.h (types, prototypes) and meta.c (classes, vtables, interface
// maps, reflection descriptors, invokers, string literals). The class records
// are what the runtime's mono API answers from. See docs/runtime.md.
using System.Text;
using Mono.Cecil;

sealed class MetaWriter
{
    readonly Gen g; readonly World w; readonly Layouts lay;
    List<TT> classes = new();
    readonly Dictionary<TT, List<MI>> methodsOf = new();
    readonly Dictionary<string, int> invokers = new();
    readonly StringBuilder inv = new();
    readonly Dictionary<MI, (int cls, int idx)> descIndex = new();
    readonly Dictionary<AssemblyDefinition, int> images = new();

    public MetaWriter(Gen g) { this.g = g; w = g.W; lay = g.Lay; }

    static bool Real(TT t) => t.K != TK.Def || t.Def != null;

    public void Close()
    {
        foreach (var m in g.Order) { if (!methodsOf.TryGetValue(m.Owner, out var l)) methodsOf[m.Owner] = l = new(); l.Add(m); }
        var work = new Queue<TT>(g.KlassUsed.Concat(g.Constructed).Concat(g.ObjUsed).Concat(g.StaticsUsed));
        var seen = new HashSet<TT>();
        while (work.Count > 0)
        {
            var t = work.Dequeue();
            if (!seen.Add(t)) continue;
            void Add(TT? x) { if (x != null && !seen.Contains(x)) work.Enqueue(x); }
            g.Klass(t);
            // Signature types of methods are not followed: a descriptor whose
            // parameter class isn't in the set just records null (KRef).
            try
            {
                var L = lay.Full(t);
                Add(w.BaseOf(t));
                if (t.K is TK.SzArray or TK.Array or TK.Ptr or TK.ByRef) Add(t.Elem);
                foreach (var (i, _) in L.Ifaces) Add(i);
                foreach (var a in t.Args) Add(a);
                if (t.IsEnum) Add(lay.EnumBase(t));
                if (t.K == TK.Def && !t.IsOpen)
                    foreach (var f in t.Def.Fields) Add(Strip(w.FieldType(t, f)));
            }
            catch (UnresolvedGeneric e) { Console.Error.WriteLine($"warning: {t.Key}: {e.Message}"); }
        }
        classes = seen.Where(Real).OrderBy(t => lay.Id(t)).ToList();
        classSet = classes.ToHashSet();
        foreach (var t in classes) { lay.Id(t); g.Klass(t); }
        foreach (var t in classes) if (t.K == TK.Def && !t.IsOpen) foreach (var a in t.Def.Fields) lay.C(w.FieldType(t, a));
        // Descriptor indices: the header's MD defines point into ML tables.
        foreach (var t in classes)
        {
            var list = new List<MI>();
            if (t.K == TK.Def && !t.IsOpen)
            {
                foreach (var md in t.Def.Methods)
                    if (!md.HasGenericParameters) list.Add(w.Method(t, md, Array.Empty<TT>()));
                if (methodsOf.TryGetValue(t, out var extra)) foreach (var x in extra) if (!list.Contains(x)) list.Add(x);
            }
            for (int i = 0; i < list.Count; i++) descIndex[list[i]] = (t.Id, i);
            mlists[t] = list;
        }
    }
    readonly Dictionary<TT, List<MI>> mlists = new();

    TT Strip(TT t) => t.K == TK.ByRef ? t.Elem : t;
    string K(TT t) => "K" + lay.Id(t);
    HashSet<TT> classSet = new();
    // Signature types of methods nothing calls may lie outside the class set.
    string KRef(TT t) => classSet.Contains(t) ? "&K" + lay.Id(t) : "0";

    // ---- header ----
    public string Header()
    {
        var sb = new StringBuilder("/* generated by netrecomp: do not edit, do not commit */\n#pragma once\n#include \"nr.h\"\n\n");
        // Value types, in field-dependency order.
        var vts = lay.Used.Where(t => Real(t) && lay.Kind(t) == SK.VT).ToList();
        foreach (var t in vts) sb.Append($"typedef struct T{t.Id} T{t.Id};\n");
        var done = new HashSet<TT>();
        var defs = new StringBuilder();
        void Def(TT t)
        {
            if (!done.Add(t)) return;
            var L = lay.Full(t);
            foreach (var (f, _) in L.Inst) if (lay.Kind(f.Type) == SK.VT) Def(f.Type);
            defs.Append($"/* {t.Key} */\n");
            defs.Append(StructBody($"struct T{t.Id}", t, L.Inst, false));
        }
        foreach (var t in vts) Def(t);
        // Defining value types can reach further value types.
        foreach (var t in lay.Used.Where(t => Real(t) && lay.Kind(t) == SK.VT).ToList()) if (!vts.Contains(t)) { sb.Append($"typedef struct T{t.Id} T{t.Id};\n"); Def(t); }
        sb.Append('\n').Append(defs);
        foreach (var t in classes.Where(t => t.K == TK.Def && !t.IsValueType && !t.IsInterface))
            sb.Append($"/* {t.Key.Replace("*/", "* /")} */\n").Append(StructBody($"typedef struct O{t.Id}", t, lay.Full(t).Inst, true));
        foreach (var t in classes.Where(t => t.K == TK.Def && lay.Full(t).Statics.Count > 0))
        {
            sb.Append($"struct S{t.Id}_t {{");
            foreach (var (f, n) in lay.Full(t).Statics) sb.Append($" {lay.C(f.Type)} {n};");
            sb.Append($" }};\nextern struct S{t.Id}_t S{t.Id};\n");
        }
        sb.Append('\n');
        foreach (var t in classes) sb.Append($"extern NrClass K{t.Id};\n");
        foreach (var m in g.Order) if (g.Bodies[m].Length > 0) sb.Append(g.Proto(m)).Append(";\n");
        foreach (var m in AllThunks()) sb.Append(g.Proto(m, "U" + g.NameOf(m)[1..])).Append(";\n");
        foreach (var kv in g.Gvms) sb.Append($"extern const NrGvm G{kv.Value};\n");
        foreach (var (f, id) in g.FieldHandles) sb.Append($"extern const NrFieldDesc FD{id};\n");
        foreach (var f in g.Rvas) sb.Append($"extern const uint8_t RVA{g.FieldHandles.First(x => x.f.Def == f.Def).id}[];\n");
        foreach (var t in classes) sb.Append($"extern const NrMethodDesc ML{t.Id}[];\n");
        foreach (var m in g.Descs)
        {
            var (c, i) = DescIndex(m);
            sb.Append($"#define MD{g.NameOf(m)[1..]} ML{c}[{i}]\n");
        }
        // The runtime's NrDelegate must match the generated Delegate layout.
        var md = classes.FirstOrDefault(t => t.K == TK.Def && t.Def.FullName == "System.MulticastDelegate");
        if (md != null)
        {
            var L = lay.Full(md);
            string F(string n) => L.Inst.First(x => x.f.Def.Name == n).cname;
            sb.Append($"typedef char nr_check_delegate[(offsetof(O{md.Id}, {F("m_target")}) == offsetof(NrDelegate, target) && offsetof(O{md.Id}, {F("prev")}) == offsetof(NrDelegate, prev)) ? 1 : -1];\n");
        }
        return sb.ToString();
    }

    IEnumerable<MI> AllThunks()
    {
        var s = new HashSet<MI>(g.Thunks);
        foreach (var t in classes.Where(t => t.IsValueType && g.Constructed.Contains(t)))
            foreach (var x in VtableEntries(t)) if (x != null && x.Owner.IsValueType && x.Def.HasThis && g.IsReached(x)) s.Add(x);
        foreach (var kv in g.Gvms) foreach (var t in g.ConstructedList) { var impl = g.GvmImpl(t, kv.Key); if (impl != null && impl.Owner.IsValueType && g.IsReached(impl)) s.Add(impl); }
        return s.OrderBy(m => m.Id);
    }

    string StructBody(string head, TT t, List<(FI f, string cname)> fields, bool header)
    {
        var sb = new StringBuilder();
        var d = t.Def;
        bool expl = d.IsExplicitLayout;
        int size = d.ClassSize > 0 ? d.ClassSize : 0;
        if (expl || d.PackingSize > 0) sb.Append($"#pragma pack(push, {(expl ? 1 : d.PackingSize)})\n");
        sb.Append(head).Append(" {");
        if (header) sb.Append(" NrClass* klass; void* sync;");
        // Inherited fields in a class come first and use their own base layout.
        var own = header ? fields.Where(f => f.f.Owner == t).ToList() : fields;
        var inherited = header ? fields.Where(f => f.f.Owner != t).ToList() : new();
        if (inherited.Count > 0 && inherited.Any(f => f.f.Owner.Def.IsExplicitLayout))
            throw new Exception("explicit-layout base class " + t.Key);
        foreach (var (f, n) in inherited) sb.Append($" {lay.C(f.Type)} {n};");
        if (expl)
        {
            sb.Append(" union {");
            int k = 0;
            foreach (var (f, n) in own)
            {
                int off = f.Def.Offset;
                sb.Append(off == 0 ? $" struct {{ {lay.C(f.Type)} {n}; }};" : $" struct {{ uint8_t _o{k}[{off}]; {lay.C(f.Type)} {n}; }};");
                k++;
            }
            if (size > 0) sb.Append($" uint8_t _size[{size}];");
            if (own.Count == 0 && size == 0) sb.Append(" uint8_t _empty;");
            sb.Append(" };");
        }
        else if (size > 0 && !header)
        {
            sb.Append(" union { struct {");
            foreach (var (f, n) in own) sb.Append($" {lay.C(f.Type)} {n};");
            if (own.Count == 0) sb.Append(" uint8_t _empty;");
            sb.Append($" }}; uint8_t _size[{size}]; }};");
        }
        else
        {
            foreach (var (f, n) in own) sb.Append($" {lay.C(f.Type)} {n};");
            if (!header && own.Count == 0) sb.Append(" uint8_t _empty;");
        }
        sb.Append(" }").Append(header ? $" O{t.Id};" : ";");
        if (expl || d.PackingSize > 0) sb.Append("\n#pragma pack(pop)");
        return sb.Append('\n').ToString();
    }

    (int, int) DescIndex(MI m)
    {
        if (descIndex.TryGetValue(m, out var x)) return x;
        throw new Exception("no descriptor for " + m.Key);
    }

    List<MI?> VtableEntries(TT t)
    {
        var L = lay.Full(t);
        var e = new List<MI?>(L.Slots);
        foreach (var (_, impls) in L.Ifaces) e.AddRange(impls);
        return e;
    }

    // ---- meta.c ----
    static int TypeCode(TT t)
    {
        switch (t.K)
        {
            case TK.SzArray: return 0x1d;
            case TK.Array: return 0x14;
            case TK.Ptr: return 0x0f;
            case TK.ByRef: return 0x10;
            case TK.FnPtr: return 0x1b;
        }
        if (t.Def.Module.Assembly.Name.Name == "mscorlib")
            switch (t.Def.FullName)
            {
                case "System.Void": return 1; case "System.Boolean": return 2; case "System.Char": return 3;
                case "System.SByte": return 4; case "System.Byte": return 5; case "System.Int16": return 6; case "System.UInt16": return 7;
                case "System.Int32": return 8; case "System.UInt32": return 9; case "System.Int64": return 0xa; case "System.UInt64": return 0xb;
                case "System.Single": return 0xc; case "System.Double": return 0xd; case "System.String": return 0xe;
                case "System.IntPtr": return 0x18; case "System.UIntPtr": return 0x19; case "System.Object": return 0x1c;
                case "System.TypedReference": return 0x16;
            }
        if (t.IsGenericInst) return 0x15;
        return t.IsValueType ? 0x11 : 0x12;
    }

    bool HasRefs(TT t, int depth = 0)
    {
        if (depth > 20) return true;
        switch (t.K)
        {
            case TK.SzArray: case TK.Array: return lay.Kind(t.Elem) == SK.P || (lay.Kind(t.Elem) == SK.VT && HasRefs(t.Elem, depth + 1));
            case TK.Ptr: case TK.FnPtr: case TK.ByRef: return false;
        }
        if (t.Def.FullName == "System.String" && t.Def.Module.Assembly.Name.Name == "mscorlib") return false;
        return lay.Full(t).Inst.Any(f => lay.Kind(f.f.Type) == SK.P || (lay.Kind(f.f.Type) == SK.VT && HasRefs(f.f.Type, depth + 1)));
    }

    string Invoker(MI m)
    {
        var ps = new List<string>();
        for (int i = 0; i < m.Def.Parameters.Count; i++)
        {
            var pt = w.ParamType(m, i);
            ps.Add(lay.Kind(pt) == SK.P ? "void*" : lay.C(pt));
        }
        var rt = lay.C(w.RetType(m));
        var key = $"{m.Def.HasThis}|{rt}|{string.Join(",", ps)}";
        if (invokers.TryGetValue(key, out var n)) return "INV" + n;
        n = invokers.Count;
        invokers[key] = n;
        var fargs = new List<string>(); var cargs = new List<string>();
        if (m.Def.HasThis) { fargs.Add("void*"); cargs.Add("obj"); }
        for (int i = 0; i < ps.Count; i++)
        {
            fargs.Add(ps[i]);
            var pt = w.ParamType(m, i);
            cargs.Add(lay.Kind(pt) == SK.P ? $"args[{i}]" : $"*({ps[i]}*)args[{i}]");
        }
        var call = $"(({rt} (*)({string.Join(", ", fargs.DefaultIfEmpty("void"))}))fn)({string.Join(", ", cargs)})";
        inv.Append($"static void INV{n}(void* fn, void* obj, void** args, void* ret) {{ (void)obj; (void)args; ");
        inv.Append(rt == "void" ? $"{call}; (void)ret; }}\n" : $"*({rt}*)ret = {call}; }}\n");
        return "INV" + n;
    }

    public string Body()
    {
        var sb = new StringBuilder("/* generated by netrecomp: do not edit, do not commit */\n#include \"nrgen.h\"\n\n");

        foreach (var a in classes.Where(t => t.K == TK.Def).Select(t => t.Def.Module.Assembly).Distinct())
            images[a] = images.Count;
        foreach (var (a, i) in images) sb.Append($"NrImage IMG{i} = {{ \"{a.Name.Name}\", \"{Path.GetFileName(a.MainModule.FileName)}\" }};\n");
        sb.Append($"NrImage* const nr_images[] = {{ {string.Join(", ", images.Values.Select(i => "&IMG" + i))} }};\nconst int32_t nr_n_images = {images.Count};\n\n");

        foreach (var t in classes.Where(t => t.K == TK.Def && lay.Full(t).Statics.Count > 0)) sb.Append($"struct S{t.Id}_t S{t.Id};\n");

        foreach (var m in AllThunks())
        {
            var ps = g.Params(m);
            var args = ps.Select((_, i) => i == 0 ? "(uint8_t*)a0 + sizeof(NrObj)" : $"a{i}");
            sb.Append(g.Proto(m, "U" + g.NameOf(m)[1..])).Append($" {{ {(lay.C(w.RetType(m)) == "void" ? "" : "return ")}{g.NameOf(m)}({string.Join(", ", args)}); }}\n");
        }

        var body = new StringBuilder();
        foreach (var t in classes) ClassRecord(body, t, mlists[t]);
        sb.Append(inv).Append(g.At.Factories).Append(body);

        sb.Append("\nNrClass* const nr_classes[] = {\n");
        foreach (var t in classes) sb.Append($"    &K{t.Id},\n");
        sb.Append($"}};\nconst int32_t nr_n_classes = {classes.Count};\n\n");

        // GVM tables
        foreach (var kv in g.Gvms)
        {
            sb.Append($"static const NrGvmEntry GE{kv.Value}[] = {{ ");
            foreach (var t in g.ConstructedList)
            {
                var impl = g.GvmImpl(t, kv.Key);
                if (impl != null && g.IsReached(impl) && classes.Contains(t))
                    sb.Append($"{{ &K{t.Id}, (void*){(impl.Owner.IsValueType && impl.Def.HasThis ? "U" + g.NameOf(impl)[1..] : g.NameOf(impl))} }}, ");
            }
            sb.Append($"{{ 0, 0 }} }};\nconst NrGvm G{kv.Value} = {{ GE{kv.Value} }};\n");
        }

        // Field handles (ldtoken field) and RVA data
        foreach (var (f, id) in g.FieldHandles)
        {
            string rva = "0"; int rsz = 0;
            if (f.Def.HasFieldRVA)
            {
                var data = f.Def.InitialValue;
                sb.Append($"const uint8_t RVA{id}[] = {{ {string.Join(",", data.Select(b => b.ToString()))}{(data.Length == 0 ? "0" : "")} }};\n");
                rva = $"RVA{id}"; rsz = data.Length;
            }
            sb.Append($"const NrFieldDesc FD{id} = {{ \"{Gen.CEsc(f.Def.Name)}\", &{K(Strip(f.Type))}, &{K(f.Owner)}, 0, {(ushort)f.Def.Attributes}, 0, 0x{f.Def.MetadataToken.ToUInt32():x}, {rva}, {rsz} }};\n");
        }

        // String literals
        sb.Append('\n');
        for (int i = 0; i < g.Strings.Count; i++)
        {
            var s = g.Strings[i];
            sb.Append($"static const uint16_t STR{i}[] = {{ {string.Join(",", s.Select(c => ((int)c).ToString()).Append("0"))} }};\n");
        }
        sb.Append($"const NrStrLit nr_strlits[] = {{ {string.Join(", ", Enumerable.Range(0, g.Strings.Count).Select(i => $"{{ STR{i}, {g.Strings[i].Length} }}"))}{(g.Strings.Count == 0 ? "{ 0, 0 }" : "")} }};\n");
        sb.Append($"void* nr_strtab[{Math.Max(1, g.Strings.Count)}];\nconst int32_t nr_n_strs = {g.Strings.Count};\n");
        return sb.ToString();
    }

    void ClassRecord(StringBuilder sb, TT t, List<MI> methods)
    {
        var L = lay.Full(t);
        var id = t.Id;
        bool cons = g.Constructed.Contains(t);
        sb.Append($"/* {t.Key} */\n");
        // supers: root first, self last
        var chain = new List<TT>();
        if (!t.IsInterface) for (TT? c = t; c != null; c = w.BaseOf(c)) chain.Insert(0, c);
        else chain.Add(t);
        sb.Append($"static NrClass* const SUP{id}[] = {{ {string.Join(", ", chain.Select(c => "&" + K(c)))} }};\n");

        // vtable + interface blocks
        int nvt = 0;
        var ifs = new List<string>();
        if (cons && !t.IsInterface)
        {
            var e = new List<string>();
            foreach (var s in L.Slots) e.Add(Fp(s));
            foreach (var (it, impls) in L.Ifaces)
            {
                ifs.Add($"{{ &{K(it)}, {e.Count} }}");
                foreach (var s in impls) e.Add(Fp(s));
            }
            nvt = e.Count;
            if (nvt > 0) sb.Append($"static void* const VT{id}[] = {{ {string.Join(", ", e)} }};\n");
        }
        else foreach (var (it, _) in L.Ifaces) ifs.Add($"{{ &{K(it)}, -1 }}");
        if (t.IsInterface && !t.IsOpen) foreach (var it in lay.AllIfaces(t).Distinct().Where(classSet.Contains)) ifs.Add($"{{ &{K(it)}, -1 }}");
        if (ifs.Count > 0) sb.Append($"static const NrIface IF{id}[] = {{ {string.Join(", ", ifs)} }};\n");

        // fields
        var fl = new List<string>();
        if (t.K == TK.Def && !t.IsOpen)
            foreach (var f in t.Def.Fields)
            {
                var ft = w.FieldType(t, f);
                string off;
                if (f.IsLiteral) off = "-1";
                else if (f.IsStatic) off = $"(int32_t)offsetof(struct S{id}_t, {L.FieldName[f]})";
                else if (Layouts.IsPrim(t) || t.IsEnum) off = "(int32_t)sizeof(NrObj)";
                else if (t.IsValueType) off = $"(int32_t)(offsetof(T{id}, {L.FieldName[f]}) + sizeof(NrObj))";
                else off = $"(int32_t)offsetof(O{id}, {L.FieldName[f]})";
                string cv = "0"; int cs = 0;
                if (f.HasConstant)
                {
                    var bytes = ConstBytes(f.Constant);
                    if (bytes != null) { cv = $"(const uint8_t[]){{ {string.Join(",", bytes.Select(b => b.ToString()).DefaultIfEmpty("0"))} }}"; cs = bytes.Length; }
                }
                fl.Add($"{{ \"{Gen.CEsc(f.Name)}\", &{K(Strip(ft))}, &K{id}, {off}, {(ushort)f.Attributes}, {(ft.K == TK.ByRef ? 1 : 0)}, 0x{f.MetadataToken.ToUInt32():x}, {cv}, {cs}, {g.At.Table(t, f, KRef)} }}");
            }
        if (fl.Count > 0) sb.Append($"static const NrFieldDesc FL{id}[] = {{\n    {string.Join(",\n    ", fl)} }};\n");

        // methods
        var ml = new List<string>();
        foreach (var m in methods)
        {
            bool live = g.IsReached(m) && g.Bodies.TryGetValue(m, out var b) && b.Length > 0;
            string ret, pars = "0", pby = "0";
            try
            {
                ret = KRef(Strip(w.RetType(m)));
                if (m.Def.Parameters.Count > 0)
                {
                    var pts = Enumerable.Range(0, m.Def.Parameters.Count).Select(i => w.ParamType(m, i)).ToList();
                    pars = $"(NrClass* const[]){{ {string.Join(", ", pts.Select(p => KRef(Strip(p))))} }}";
                    pby = $"(const uint8_t[]){{ {string.Join(", ", pts.Select(p => p.K == TK.ByRef ? "1" : "0"))} }}";
                }
            }
            catch (Exception e) when (e is UnresolvedGeneric or KeyNotFoundException) { ret = "0"; }
            int slot = m.Def.IsVirtual && L.SlotOf.TryGetValue(m.Def, out var s) ? s : -1;
            var fn = live ? $"(void*){g.NameOf(m)}" : "0";
            var invk = live ? Invoker(m) : "0";
            ml.Add($"{{ &K{id}, \"{Gen.CEsc(m.Def.Name)}\", {fn}, {invk}, {(ushort)m.Def.Attributes}, {(ushort)m.Def.ImplAttributes}, {m.Def.Parameters.Count}, {slot}, {ret}, {pars}, {pby}, 0x{m.Def.MetadataToken.ToUInt32():x}, {(m.MArgs.Length == 0 ? g.At.Table(t, m.Def, KRef) : "0, 0")} }}");
        }
        sb.Append($"const NrMethodDesc ML{id}[] = {{\n    {string.Join(",\n    ", ml.DefaultIfEmpty("{ 0 }"))} }};\n");

        // the record
        uint flags = 0;
        if (t.IsValueType) flags |= 1;
        if (t.IsEnum) flags |= 2;
        if (t.IsInterface) flags |= 4;
        if (t.K == TK.Def && t.Def.IsAbstract) flags |= 8;
        if (t.K is TK.SzArray or TK.Array) flags |= 16;
        if (HasRefs(t)) flags |= 32;
        if (t.K == TK.Def && t.Def.IsSealed) flags |= 64;
        if (t.IsGenericInst) flags |= 128;
        if (g.IsDelegate(t)) flags |= 256;
        if (g.IsNullable(t)) flags |= 512;
        if (t.K == TK.Def && !t.IsValueType && L.Slots.Any(s => s != null && s.Def.Name == "Finalize" && s.Owner.Def.FullName != "System.Object")) flags |= 1024;
        if (t.K == TK.Def && t.Def.FullName == "System.String" && t.Def.Module.Assembly.Name.Name == "mscorlib") flags |= 2048;
        if (cons) flags |= 4096;
        if (t.K is TK.Ptr or TK.FnPtr) flags |= 8192;

        string inst, vsize, esize = "0";
        switch (t.K)
        {
            case TK.SzArray: case TK.Array:
                inst = "16"; vsize = "sizeof(void*)";
                esize = lay.Kind(t.Elem) == SK.VT ? $"sizeof(T{lay.Id(t.Elem)})" : $"sizeof({lay.C(t.Elem)})";
                break;
            case TK.Ptr: case TK.FnPtr: case TK.ByRef: inst = "sizeof(NrObj)"; vsize = "sizeof(void*)"; break;
            default:
                if (t.IsValueType)
                {
                    var c = lay.C(t);
                    vsize = c == "void" ? "0" : $"sizeof({c})";
                    inst = c == "void" ? "sizeof(NrObj)" : $"(sizeof(NrObj) + sizeof({c}))";
                }
                else if (t.IsInterface) { inst = "sizeof(NrObj)"; vsize = "sizeof(void*)"; }
                else { inst = $"sizeof(O{id})"; vsize = "sizeof(void*)"; }
                break;
        }
        string elem = "0", cast = "0";
        if (t.K is TK.SzArray or TK.Array or TK.Ptr or TK.ByRef) { elem = "&" + K(t.Elem); cast = t.Elem.IsEnum ? "&" + K(lay.EnumBase(t.Elem)) : elem; }
        else if (t.IsEnum) { elem = cast = "&" + K(lay.EnumBase(t)); }
        string gargs = "0";
        if (t.Args.Length > 0) { gargs = $"GA{id}"; sb.Append($"static NrClass* const GA{id}[] = {{ {string.Join(", ", t.Args.Select(a => "&" + K(a)))} }};\n"); }
        string nested = "0";
        if (t.K == TK.Def && t.Def.DeclaringType != null && !t.Def.DeclaringType.HasGenericParameters)
        {
            var dt = w.Inst(t.Def.DeclaringType, Array.Empty<TT>());
            if (classes.Contains(dt)) nested = "&" + K(dt);
        }
        string cctor = "0";
        if (g.HasCctor(t))
        {
            var cm = w.Method(t, t.Def.Methods.First(x => x.IsConstructor && x.IsStatic), Array.Empty<TT>());
            if (g.IsReached(cm)) cctor = g.NameOf(cm);
        }
        var name = t.K switch
        {
            TK.Def => t.Def.Name,
            TK.SzArray => ElemName(t.Elem) + "[]",
            TK.Array => ElemName(t.Elem) + "[" + new string(',', t.Rank - 1) + "]",
            TK.Ptr => ElemName(t.Elem) + "*",
            TK.ByRef => ElemName(t.Elem) + "&",
            _ => "fnptr",
        };
        var ns = t.K == TK.Def ? t.Def.Namespace : t.K is TK.FnPtr ? "" : NsOf(t);
        var img = t.K == TK.Def ? $"&IMG{images[t.Def.Module.Assembly]}" : NsImg(t);
        var tc = TypeCode(t);
        bool statics = t.K == TK.Def && L.Statics.Count > 0;
        sb.Append($"NrClass K{id} = {{ &K{id}, \"{Gen.CEsc(name)}\", \"{Gen.CEsc(ns)}\", {(w.BaseOf(t) is TT bt && !t.IsInterface ? "&" + K(bt) : "0")}, {elem}, {cast}, {nested}, 0,\n");
        sb.Append($"    {gargs}, {t.Args.Length}, {t.Rank}, {chain.Count - 1}, 0x{flags:x}, 0x{(t.K == TK.Def ? (uint)t.Def.Attributes : 0):x}, {inst}, {vsize}, {esize},\n");
        sb.Append($"    SUP{id}, {(ifs.Count > 0 ? "IF" + id : "0")}, {ifs.Count}, {nvt}, {(nvt > 0 ? "VT" + id : "0")}, {(cctor == "0" ? "0" : "(void(*)(void))" + cctor)}, 0, 0,\n");
        sb.Append($"    {(statics ? "&S" + id : "0")}, {(statics ? $"sizeof(S{id})" : "0")}, {(fl.Count > 0 ? "FL" + id : "0")}, {fl.Count}, {methods.Count}, ML{id}, {img}, 0x{(t.K == TK.Def ? t.Def.MetadataToken.ToUInt32() : 0):x},\n");
        sb.Append($"    {{ &K{id}, 0, {tc} }}, {{ &K{id}, 1, {tc} }}, 0, 0, 0, {(t.K == TK.Def && !t.IsOpen ? g.At.Table(t, t.Def, KRef) : "0, 0")} }};\n\n");
    }

    string ElemName(TT t) => t.K switch
    {
        TK.Def => t.Def.Name,
        TK.SzArray => ElemName(t.Elem) + "[]",
        TK.Array => ElemName(t.Elem) + "[" + new string(',', t.Rank - 1) + "]",
        TK.Ptr => ElemName(t.Elem) + "*",
        TK.ByRef => ElemName(t.Elem) + "&",
        _ => "fnptr",
    };
    string NsOf(TT t) => t.K == TK.Def ? t.Def.Namespace : t.K == TK.FnPtr ? "" : NsOf(t.Elem);
    string NsImg(TT t) => t.K == TK.Def ? $"&IMG{images[t.Def.Module.Assembly]}" : t.K == TK.FnPtr ? "0" : NsImg(t.Elem);

    string Fp(MI? m)
    {
        if (m == null || m.Def.IsAbstract || !g.IsReached(m) || g.Bodies[m].Length == 0) return "0";
        return "(void*)" + (m.Owner.IsValueType && m.Def.HasThis ? "U" + g.NameOf(m)[1..] : g.NameOf(m));
    }

    static byte[]? ConstBytes(object? c) => c switch
    {
        null => Array.Empty<byte>(),
        bool b => new[] { (byte)(b ? 1 : 0) },
        char ch => BitConverter.GetBytes(ch),
        sbyte v => new[] { (byte)v }, byte v => new[] { v },
        short v => BitConverter.GetBytes(v), ushort v => BitConverter.GetBytes(v),
        int v => BitConverter.GetBytes(v), uint v => BitConverter.GetBytes(v),
        long v => BitConverter.GetBytes(v), ulong v => BitConverter.GetBytes(v),
        float v => BitConverter.GetBytes(v), double v => BitConverter.GetBytes(v),
        string s => System.Text.Encoding.Unicode.GetBytes(s),
        _ => null,
    };
